"""Investigation report / export bundle (Phase 11, Phase J).

The export is produced from persisted records the caller may see. It is a
convenience copy generated by this application: it is NOT independently
authenticated, signed or certified, and the manifest hashes only let a
recipient detect later changes to the files in the bundle.

Reproducibility: `content_sha256` is computed over the canonical report body
excluding generation metadata (generated_at, generated_by, export_id), so two
exports of unchanged data share it. `generated_at` is when the report was
built and says nothing about when any evidence was created or captured.
"""
from __future__ import annotations

import hashlib
import io
import json
import zipfile
from datetime import datetime, timezone
from typing import Optional

from sqlalchemy import select
from sqlalchemy.orm import Session

from app.core.security import AuthenticatedUser
from app.cv import storage
from app.models.assessment_review import AssessmentReview
from app.models.investigation import Investigation
from app.models.media_asset import MediaAsset
from app.services import audit_service, evidence_registry_service as registry
from app.services import investigation_links_service as links
from app.services import investigation_notes_service as notes_svc
from app.services import investigation_service, investigation_timeline_service as timeline_svc
from app.services.timeutil import iso
from app.services.workspace_errors import invalid

EXPORT_SCHEMA_VERSION = "1.0"
MAX_MEDIA_FILE_BYTES = 10 * 1024 * 1024
MAX_BUNDLE_MEDIA_BYTES = 25 * 1024 * 1024
MAX_MEDIA_FILES = 25
NOT_AUTHENTICATED_NOTICE = (
    "This report was generated by the AEGIS application from stored records. It is not independently authenticated, "
    "signed or certified, and it is not a legal chain-of-custody document. Hashes in the manifest only allow detecting "
    "later changes to the files listed. The generation time is not an evidence time."
)


def _canonical(obj) -> bytes:
    return json.dumps(obj, sort_keys=True, separators=(",", ":"), default=str).encode("utf-8")


def _sha(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def build_report(db: Session, investigation: Investigation, user: AuthenticatedUser, *, include_media: bool = False) -> tuple[dict, list[tuple[str, bytes]]]:
    org = investigation.organization_id
    omitted: list[dict] = []
    recs = links.effective_records(db, investigation)

    linked_records, evidence_index, assessments = [], [], []
    media_candidates: dict[str, MediaAsset] = {}
    for r in recs:
        row = r["row"]
        if row is None:
            omitted.append({"record_type": r["record_type"], "record_id": r["record_id"], "reason": "record_not_found_or_not_in_organization"})
            continue
        if r["record_type"] == "evidence" and not registry.evidence_visible(user, row):
            omitted.append({"record_type": "evidence", "record_id": row.id, "reason": "access_classification_restricted"})
            continue
        linked_records.append({**links.describe(r["record_type"], row), "origin": r["origin"]})
        if r["record_type"] == "evidence":
            checks = registry.list_integrity_checks(db, row)
            last = checks[-1] if checks else None
            evidence_index.append({
                "evidence_id": row.id, "provenance": registry.build_provenance(db, row),
                "superseded_by": row.superseded_by_evidence_id,
                "integrity_checks_count": len(checks),
                "latest_integrity_check": ({"result": last.result, "checked_at": iso(last.created_at), "recorded_hash": last.recorded_hash,
                                            "computed_hash": last.computed_hash} if last else None),
            })
            if row.media_asset_id:
                m = db.get(MediaAsset, row.media_asset_id)
                if m is not None and m.organization_id == org:
                    media_candidates[m.id] = m
        elif r["record_type"] == "media_asset":
            media_candidates[row.id] = row
        elif r["record_type"] == "assessment":
            reviews = db.execute(select(AssessmentReview).where(AssessmentReview.assessment_id == row.id, AssessmentReview.organization_id == org)
                                 .order_by(AssessmentReview.created_at.asc(), AssessmentReview.id.asc())).scalars().all()
            assessments.append({
                "assessment_id": row.id, "title": row.title, "status": row.status, "current_version": row.version,
                "created_at": iso(row.created_at),
                "reviews": [{"review_id": v.id, "assessment_version": v.assessment_version, "decision": v.decision,
                             "notes": v.notes, "information_flags": list(v.information_flags or []), "reviewed_at": iso(v.created_at),
                             "reviewer_user_id": v.reviewer_user_id} for v in reviews],
            })

    note_rows = notes_svc.list_notes(db, investigation)
    notes_out = [{
        "note_id": n.id, "note_kind": n.note_kind, "body": n.body, "tags": list(n.tags or []), "evidence_id": n.evidence_id,
        "parent_note_id": n.parent_note_id, "author_user_id": n.author_user_id, "version": n.version,
        "created_at": iso(n.created_at), "resolution_status": n.resolution_status,
        "revisions": [{"version": rv.version, "body": rv.body, "changed_at": iso(rv.created_at)} for rv in notes_svc.list_revisions(db, n)],
    } for n in note_rows]

    tl = timeline_svc.sort_entries(timeline_svc.build_entries(db, investigation))[: timeline_svc.MAX_ENTRIES]
    tl_out = [{k: v for k, v in e.items() if k != "_sort"} for e in tl]

    files: list[tuple[str, bytes]] = []
    media_manifest: list[dict] = []
    if include_media:
        total = 0
        for mid in sorted(media_candidates):
            m = media_candidates[mid]
            if len(files) >= MAX_MEDIA_FILES:
                omitted.append({"record_type": "media_asset", "record_id": m.id, "reason": "export_file_count_limit"})
                continue
            if m.byte_size > MAX_MEDIA_FILE_BYTES or total + m.byte_size > MAX_BUNDLE_MEDIA_BYTES:
                omitted.append({"record_type": "media_asset", "record_id": m.id, "reason": "export_size_limit"})
                continue
            try:
                data = storage.read_bytes(m.storage_key)  # controlled storage key, traversal-checked
            except (FileNotFoundError, storage.PathTraversalError, OSError):
                omitted.append({"record_type": "media_asset", "record_id": m.id, "reason": "original_unavailable"})
                continue
            digest = _sha(data)
            if digest != m.content_hash:
                omitted.append({"record_type": "media_asset", "record_id": m.id, "reason": "integrity_mismatch_not_exported"})
                continue
            ext = (m.declared_filename.rsplit(".", 1)[-1].lower() if "." in m.declared_filename else "bin")
            ext = "".join(c for c in ext if c.isalnum())[:8] or "bin"
            path = f"media/{digest}.{ext}"
            files.append((path, data))
            total += len(data)
            media_manifest.append({"path": path, "sha256": digest, "bytes": len(data), "media_asset_id": m.id})
    else:
        for mid in sorted(media_candidates):
            omitted.append({"record_type": "media_asset", "record_id": mid, "reason": "media_bytes_not_requested"})

    body = {
        "report_type": "aegis.investigation_report", "schema_version": EXPORT_SCHEMA_VERSION,
        "investigation": {
            "id": investigation.id, "title": investigation.title, "description": investigation.description,
            "purpose": investigation.purpose, "scope": investigation.scope, "status": investigation.status,
            "priority": investigation.priority, "tags": list(investigation.tags or []), "review_status": investigation.review_status,
            "closure_reason": investigation.closure_reason, "created_at": iso(investigation.created_at),
            "closed_at": iso(investigation.closed_at), "archived_at": iso(investigation.archived_at),
            "owner_user_id": investigation.assigned_user_id,
        },
        "members": [{"user_id": m.user_id, "role": m.role} for m in investigation_service.list_members(db, investigation)],
        "status_history": [{"from": h.from_status, "to": h.to_status, "reason": h.reason, "at": iso(h.created_at), "by": h.changed_by_user_id}
                           for h in investigation_service.list_status_history(db, investigation)],
        "linked_records": linked_records, "evidence_index": evidence_index, "assessments": assessments,
        "notes": notes_out, "timeline": tl_out, "timeline_notice": timeline_svc.NO_CAUSATION_NOTICE,
        "omitted_artifacts": sorted(omitted, key=lambda o: (o["record_type"], o["record_id"], o["reason"])),
        "integrity_notice": registry.INTEGRITY_DISCLAIMER,
    }
    content_sha = _sha(_canonical(body))
    report = {
        **body,
        "generation": {"generated_at": datetime.now(timezone.utc).isoformat().replace("+00:00", "Z"), "generated_by_user_id": user.id,
                       "note": "Generation time only; unrelated to when any evidence was captured, ingested or reviewed."},
        "content_sha256": content_sha,
        "authenticity_notice": NOT_AUTHENTICATED_NOTICE,
    }
    return report, files


def export_investigation(db: Session, investigation: Investigation, user: AuthenticatedUser, *, fmt: str, include_media: bool, request_id: Optional[str]):
    if fmt not in ("json", "zip"):
        raise invalid("format must be 'json' or 'zip'")
    if include_media and fmt != "zip":
        raise invalid("include_media requires format=zip")
    report, media_files = build_report(db, investigation, user, include_media=include_media)
    report_bytes = json.dumps(report, indent=2, sort_keys=True, default=str).encode("utf-8")
    manifest = {
        "manifest_version": "1.0", "algorithm": "sha256",
        "files": [{"path": "report.json", "sha256": _sha(report_bytes), "bytes": len(report_bytes)}]
                 + [{"path": p, "sha256": _sha(b), "bytes": len(b)} for p, b in media_files],
        "omitted_artifacts": report["omitted_artifacts"],
        "note": "manifest.json is not listed in its own manifest. " + NOT_AUTHENTICATED_NOTICE,
    }
    audit_service.record(
        db, action="investigation.export", actor_user_id=user.id, organization_id=investigation.organization_id,
        target_type="investigation", target_id=investigation.id, request_id=request_id,
        context_metadata={"format": fmt, "include_media": include_media, "media_files": len(media_files),
                          "omitted": len(report["omitted_artifacts"]), "content_sha256": report["content_sha256"]},
    )
    db.flush()
    if fmt == "json":
        return {"report": report, "manifest": manifest}, None
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        def put(name: str, data: bytes):
            zi = zipfile.ZipInfo(name, date_time=(1980, 1, 1, 0, 0, 0))
            zi.compress_type = zipfile.ZIP_DEFLATED
            z.writestr(zi, data)
        put("README.txt", (NOT_AUTHENTICATED_NOTICE + "\nSee manifest.json for file hashes.\n").encode())
        put("report.json", report_bytes)
        put("manifest.json", json.dumps(manifest, indent=2, sort_keys=True).encode())
        for p, b in media_files:
            put(p, b)
    return None, buf.getvalue()
