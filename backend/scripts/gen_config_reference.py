"""Regenerate docs/operations/CONFIGURATION_REFERENCE.md from app.core.config.Settings.

    python scripts/gen_config_reference.py            # rewrite the file
    python scripts/gen_config_reference.py --check    # exit 1 if it is stale

Lists every environment variable the backend reads, with type and built-in
default. A test (tests/test_release_config.py) fails when a Settings field is
missing from the committed reference, so the document cannot silently rot.
"""
from __future__ import annotations

import os
import sys
import types
import typing

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

from app.core.config import Settings  # noqa: E402

OUT = os.path.join(os.path.dirname(__file__), "..", "..", "docs", "operations", "CONFIGURATION_REFERENCE.md")
SENSITIVE = ("SECRET", "API_KEY", "PASSWORD", "TOKEN")
PRODUCTION_REQUIRED = {
    "ENVIRONMENT": "set to `production`",
    "SECRET_KEY": "REQUIRED: random, >= 32 characters; the app refuses to start otherwise",
    "DATABASE_URL": "PostgreSQL URL recommended (SQLite is flagged by the startup review)",
    "CORS_ALLOWED_ORIGINS": "explicit https origins; `*` is refused in production",
    "CV_MEDIA_STORAGE_ROOT": "absolute path on a persistent, backed-up volume",
}


def _type_name(annotation) -> str:
    # Version-independent: Python 3.14 reports Optional[X] as "Union", 3.13 as "Optional".
    if typing.get_origin(annotation) in (typing.Union, types.UnionType) and type(None) in typing.get_args(annotation):
        return "Optional"
    return getattr(annotation, "__name__", str(annotation)).replace("typing.", "")


def render() -> str:
    lines = [
        "# Configuration reference (generated)",
        "",
        "Generated by `python scripts/gen_config_reference.py` from `app/core/config.py`; do not edit by hand.",
        "Every variable is read from the process environment (or a `.env` file in `backend/`). Names are case-sensitive.",
        "Defaults shown are the built-in development defaults, **not** production recommendations; "
        "the rows marked in the last column must be set deliberately for production. Secret values are never listed.",
        "",
        "| Variable | Type | Built-in default | Production note |",
        "|---|---|---|---|",
    ]
    for name, field in Settings.model_fields.items():
        default = field.default
        if any(s in name for s in SENSITIVE) and "EXPIRE" not in name and name != "SECRET_KEY" and isinstance(default, str) and default:
            shown = "`<redacted>`"
        elif name == "SECRET_KEY":
            shown = "`dev-only-secret-change-me-in-production` (development placeholder; refused in production)"
        else:
            shown = f"`{default}`" if default not in ("",) else "_(empty)_"
        shown = shown.replace("|", "\\|")
        ann = _type_name(field.annotation).replace("|", "\\|")
        note = PRODUCTION_REQUIRED.get(name, "")
        lines.append(f"| `{name}` | {ann} | {shown} | {note} |")
    lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    text = render()
    path = os.path.normpath(OUT)
    if "--check" in sys.argv:
        raise SystemExit(0 if os.path.exists(path) and open(path, encoding="utf-8").read() == text else 1)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print(f"wrote {path} ({len(text.splitlines())} lines)")
